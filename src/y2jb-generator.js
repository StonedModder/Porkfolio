'use strict';

const fs = require('fs');
const fsp = require('fs/promises');
const path = require('path');
const zlib = require('zlib');

const REQUIRED_TEMPLATE_FILES = [
  'main.js',
  'update.js',
  path.join('ps5_autoloader', 'autoload.txt'),
];

function requireSafeRelativePath(value, label) {
  const normalized = String(value || '').replace(/\\/g, '/').trim();
  if (!normalized || normalized.startsWith('/') || normalized.includes('\0')) {
    throw new Error(`${label} must be a non-empty relative path.`);
  }
  const parts = normalized.split('/');
  if (parts.some((part) => !part || part === '.' || part === '..')) {
    throw new Error(`${label} must not contain traversal segments.`);
  }
  return parts.join('/');
}

function formatAutoload(entries) {
  const usable = (entries || []).filter((entry) => String(entry?.value || '').trim());
  const lines = [
    '#',
    '# Generated by Porkfolio Y2JB Generator',
    '# Payload names are case-sensitive. Delay commands are milliseconds.',
    '#',
    '',
  ];

  for (const entry of usable) {
    const value = String(entry.value).trim();
    if (entry.type === 'delay') {
      if (!/^\d+$/.test(value)) throw new Error(`Delay must be milliseconds: ${value}`);
      lines.push(`!${value}`);
    } else if (entry.type === 'message') {
      lines.push(`@ ${value.replace(/[\r\n]/g, ' ')}`);
    } else if (entry.type === 'payload') {
      lines.push(requireSafeRelativePath(value, 'Payload path'));
    } else {
      throw new Error(`Unsupported autoload entry type: ${entry.type}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

async function assertTemplate(templateDir) {
  const missing = [];
  for (const file of REQUIRED_TEMPLATE_FILES) {
    try { await fsp.access(path.join(templateDir, file)); }
    catch (_) { missing.push(file.replace(/\\/g, '/')); }
  }
  if (missing.length) throw new Error(`Y2JB template is missing: ${missing.join(', ')}`);
}

async function copyTemplate(templateDir, workspaceDir) {
  await fsp.rm(workspaceDir, { recursive: true, force: true });
  await fsp.mkdir(workspaceDir, { recursive: true });
  await fsp.cp(templateDir, workspaceDir, { recursive: true, force: true });
}

async function buildUpdateInfo(dir, baseDir = dir) {
  const lines = [];
  const entries = await fsp.readdir(dir, { withFileTypes: true });
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.') || entry.name === 'update-info.txt') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      lines.push(...await buildUpdateInfo(full, baseDir));
    } else {
      const stat = await fsp.stat(full);
      lines.push(`${path.relative(baseDir, full).replace(/\\/g, '/')}|${stat.size}`);
    }
  }
  return lines;
}

async function zipEntries(dir, baseDir = dir) {
  const result = [];
  const entries = await fsp.readdir(dir, { withFileTypes: true });
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    const rel = path.relative(baseDir, full).replace(/\\/g, '/');
    if (entry.isDirectory()) {
      result.push({ full, rel: `${rel}/`, directory: true });
      result.push(...await zipEntries(full, baseDir));
    } else {
      result.push({ full, rel, directory: false });
    }
  }
  return result;
}

const CRC32_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let i = 0; i < 256; i += 1) {
    let value = i;
    for (let bit = 0; bit < 8; bit += 1) value = value & 1 ? (0xedb88320 ^ (value >>> 1)) : (value >>> 1);
    table[i] = value >>> 0;
  }
  return table;
})();

function crc32(buffer) {
  let crc = 0xffffffff;
  for (const byte of buffer) crc = CRC32_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

function dosDateTime(date) {
  const year = Math.max(1980, date.getFullYear());
  return {
    time: (date.getHours() << 11) | (date.getMinutes() << 5) | Math.floor(date.getSeconds() / 2),
    date: ((year - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate(),
  };
}

async function createPs5SafeZip(sourceDir, outputZip) {
  const chunks = [];
  const central = [];
  let offset = 0;
  for (const entry of await zipEntries(sourceDir)) {
    const name = Buffer.from(entry.rel, 'ascii');
    if (name.length !== entry.rel.length) throw new Error(`ZIP path must be ASCII: ${entry.rel}`);
    const stat = await fsp.stat(entry.full);
    const raw = entry.directory ? Buffer.alloc(0) : await fsp.readFile(entry.full);
    const compressed = entry.directory ? Buffer.alloc(0) : zlib.deflateRawSync(raw, { level: 6 });
    if (offset > 0xffffffff || raw.length > 0xffffffff) throw new Error('ZIP64 is not supported.');
    const dt = dosDateTime(stat.mtime);
    const method = entry.directory ? 0 : 8;
    const crc = entry.directory ? 0 : crc32(raw);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(entry.directory ? 10 : 20, 4);
    local.writeUInt16LE(0, 6);
    local.writeUInt16LE(method, 8);
    local.writeUInt16LE(dt.time, 10);
    local.writeUInt16LE(dt.date, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(compressed.length, 18);
    local.writeUInt32LE(raw.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    chunks.push(local, name, compressed);
    central.push({ name, method, crc, compressed: compressed.length, raw: raw.length, time: dt.time, date: dt.date, offset, directory: entry.directory });
    offset += local.length + name.length + compressed.length;
  }
  const centralStart = offset;
  for (const entry of central) {
    const header = Buffer.alloc(46);
    header.writeUInt32LE(0x02014b50, 0);
    header.writeUInt16LE(0x031e, 4);
    header.writeUInt16LE(entry.directory ? 10 : 20, 6);
    header.writeUInt16LE(0, 8);
    header.writeUInt16LE(entry.method, 10);
    header.writeUInt16LE(entry.time, 12);
    header.writeUInt16LE(entry.date, 14);
    header.writeUInt32LE(entry.crc, 16);
    header.writeUInt32LE(entry.compressed, 20);
    header.writeUInt32LE(entry.raw, 24);
    header.writeUInt16LE(entry.name.length, 28);
    header.writeUInt16LE(0, 30);
    header.writeUInt16LE(0, 32);
    header.writeUInt16LE(0, 34);
    header.writeUInt16LE(entry.directory ? 0 : 1, 36);
    header.writeUInt32LE(entry.directory ? 0x41ff0010 : 0x81ff0000, 38);
    header.writeUInt32LE(entry.offset, 42);
    chunks.push(header, entry.name);
    offset += header.length + entry.name.length;
  }
  const centralSize = offset - centralStart;
  if (central.length > 0xffff || centralStart > 0xffffffff || centralSize > 0xffffffff) throw new Error('ZIP64 is not supported.');
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(central.length, 8);
  end.writeUInt16LE(central.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(centralStart, 16);
  chunks.push(end);
  await fsp.mkdir(path.dirname(outputZip), { recursive: true });
  await fsp.writeFile(outputZip, Buffer.concat(chunks));
  return central.map((entry) => entry.name.toString('ascii'));
}

function validateZip(zipBuffer) {
  if (zipBuffer.readUInt32LE(0) !== 0x04034b50) throw new Error('Generated file is not a ZIP local-file archive.');
  const eocd = zipBuffer.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  if (eocd < 0) throw new Error('Generated ZIP has no end-of-central-directory record.');
  return true;
}

async function buildY2jbUpdate({ templateDir, workspaceDir, outputZip, entries, payloadFiles = [] }) {
  await assertTemplate(templateDir);
  await copyTemplate(templateDir, workspaceDir);
  const autoloaderDir = path.join(workspaceDir, 'ps5_autoloader');
  const autoload = formatAutoload(entries);
  await fsp.writeFile(path.join(autoloaderDir, 'autoload.txt'), autoload, 'utf8');

  const referenced = new Set((entries || []).filter((entry) => entry.type === 'payload').map((entry) => requireSafeRelativePath(entry.value, 'Payload path')));
  const supplied = new Map();
  for (const payload of payloadFiles) {
    const rel = requireSafeRelativePath(payload.name, 'Payload filename');
    supplied.set(rel, payload.data);
  }
  for (const rel of referenced) {
    const destination = path.join(autoloaderDir, ...rel.split('/'));
    if (supplied.has(rel)) {
      await fsp.mkdir(path.dirname(destination), { recursive: true });
      await fsp.writeFile(destination, supplied.get(rel));
    }
    try { await fsp.access(destination); }
    catch (_) { throw new Error(`Autoload references missing payload: ${rel}`); }
  }

  const updateInfoLines = await buildUpdateInfo(workspaceDir);
  const updateInfo = `${updateInfoLines.join('\n')}\n`;
  await fsp.writeFile(path.join(workspaceDir, 'update-info.txt'), updateInfo, 'utf8');
  const zipEntriesList = await createPs5SafeZip(workspaceDir, outputZip);
  validateZip(await fsp.readFile(outputZip));
  return { outputZip, entries: zipEntriesList, entryCount: zipEntriesList.length, updateInfo };
}

module.exports = { buildY2jbUpdate, createPs5SafeZip, formatAutoload, validateZip };
